// Regenerates ui/src/bindings/{schema,ipc}.ts from the JSON Schemas the app dumps.
//
//   npm run bindings                      dumps with `cargo run` (debug build), then compiles
//   npm run bindings -- --app <app.exe>   dumps with an already built app.exe
//   ... --out <dir>                       writes all four files to <dir> instead (the M9 gate
//                                         regenerates into a scratch folder and compares bytes)
//
// The dumped schema.json and ipc.json are committed next to the .ts files, so a change in the
// Rust types shows up as a diff in both. Regenerating an unchanged tree must give no diff
// (M9 gate e). Only project-local tools run: the app itself and json-schema-to-typescript.
import { spawnSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { compile } from 'json-schema-to-typescript';

const appDir = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');

function option(name) {
  const i = process.argv.indexOf(name);
  if (i < 0) return undefined;
  const value = process.argv[i + 1];
  if (!value || value.startsWith('--')) throw new Error(`${name} needs a value`);
  return value;
}

const outArg = option('--out');
const bindingsDir = outArg ? resolve(outArg) : join(appDir, 'ui', 'src', 'bindings');

function dump() {
  const app = option('--app');
  const [cmd, args] = app
    ? [resolve(app), ['--dump-schema', bindingsDir]]
    : ['cargo', ['run', '-q', '-p', 'app', '--', '--dump-schema', bindingsDir]];
  const r = spawnSync(cmd, args, { cwd: appDir, stdio: 'inherit' });
  if (r.error) throw r.error;
  if (r.status !== 0) throw new Error(`${cmd} exited with ${r.status}`);
}

// json-schema-to-typescript reads draft-07: `definitions` rather than `$defs`, and tuples as an
// `items` array rather than `prefixItems`. This is a faithful translation; nothing is dropped.
function toDraft07(node) {
  if (Array.isArray(node)) return node.map(toDraft07);
  if (node === null || typeof node !== 'object') return node;
  const out = {};
  for (const [k, v] of Object.entries(node)) {
    if (k === '$schema') continue;
    if (k === '$defs') out.definitions = toDraft07(v);
    else if (k === '$ref' && typeof v === 'string') out.$ref = v.replace('#/$defs/', '#/definitions/');
    else if (k === 'prefixItems') {
      out.items = toDraft07(v);
      if (node.items === false) out.additionalItems = false;
    } else if (k === 'items' && 'prefixItems' in node) continue;
    else out[k] = toDraft07(v);
  }
  return out;
}

async function generate(name) {
  const source = JSON.parse(readFileSync(join(bindingsDir, `${name}.json`), 'utf8'));
  const schema = toDraft07(source);
  // Name each definition after its key so the generated type names are the Rust type names.
  for (const [key, def] of Object.entries(schema.definitions ?? {})) def.title ??= key;
  const ts = await compile(schema, schema.title, {
    bannerComment: `/* Generated by ui/scripts/gen-bindings.mjs from ${name}.json (app.exe --dump-schema). Do not edit. */`,
    additionalProperties: false,
    unreachableDefinitions: true,
    strictIndexSignatures: true,
    format: true,
    style: { singleQuote: true, printWidth: 100, endOfLine: 'lf' },
  });
  writeFileSync(join(bindingsDir, `${name}.ts`), ts.replace(/\r\n/g, '\n'));
  console.log(`wrote ${join(bindingsDir, `${name}.ts`)}`);
}

dump();
for (const name of ['schema', 'ipc']) await generate(name);
