# One exact text edit of a file, which must match exactly once.
function Edit-Once([string]$file, [string]$old, [string]$new) {
    $text = [IO.File]::ReadAllText($file)
    $n = ([regex]::Matches($text, [regex]::Escape($old))).Count
    if ($n -ne 1) { throw "edit of ${file}: '$old' matches $n times, not once" }
    [IO.File]::WriteAllText($file, $text.Replace($old, $new), (New-Object Text.UTF8Encoding $false))
}
# Runs an executable with a hard time limit. Returns its exit code, or 'TIMEOUT' (which no check
# accepts) after killing it.
function Invoke-Solver([string]$exe, [string]$dir, [string[]]$argv, [int]$limitSec = 300) {
    $p = Start-Process -FilePath $exe -ArgumentList $argv -WorkingDirectory $dir -NoNewWindow -PassThru `
        -RedirectStandardOutput (Join-Path $dir '_stdout.txt') -RedirectStandardError (Join-Path $dir '_stderr.txt')
    $null = $p.Handle   # keeps ExitCode readable once the process has ended
    if (-not $p.WaitForExit($limitSec * 1000)) {
        Stop-Process -Id $p.Id -Force -ErrorAction SilentlyContinue
        Write-Host "      | TIMEOUT: $exe in $dir ran over $limitSec s and was killed"
        return 'TIMEOUT'
    }
    $p.WaitForExit()
    return $p.ExitCode
}
function Get-Outputs([string]$dir, [string[]]$inputs) {
    $h = @{}
    Get-ChildItem $dir -Recurse -File |
        Where-Object { $_.Name -notin $inputs -and $_.Name -notlike '_std*.txt' } |
        ForEach-Object { $h[$_.FullName.Substring($dir.Length + 1)] = (Get-FileHash $_.FullName -Algorithm SHA256).Hash }
    return $h
}
function Compare-Outputs($a, $b) {
    $keys = @($a.Keys) + @($b.Keys) | Sort-Object -Unique
    return @($keys | Where-Object { $a[$_] -ne $b[$_] })
}
# .csbin (RSBIN surface receivers) is written by dumping whole C structs, padding included, so two
# runs of the SAME executable differ in 2 bytes per 8-byte record (verified 2026-09-23). Bytes are
# meaningless there; M1 checks the same files at the same sizes, and M2 compares them decoded.
function Get-Sizes([string]$dir) {
    $h = @{}
    Get-ChildItem $dir -Recurse -File -Filter *.csbin | ForEach-Object { $h[$_.FullName.Substring($dir.Length + 1)] = $_.Length }
    return $h
}
function Get-Sha([string]$path) { Get-RawSha256 $path }
# The first 16 hex digits of a hash, or what came instead (an error text) as it is.
function Short($h) { if ("$h" -match '^[0-9a-f]{64}$') { "$h".Substring(0, 16) } else { "$h" } }

# How many bytes two PE files differ in outside their link timestamps (the fields the code sha256
# zeroes, solvers/pe-fingerprint.ps1); -1 when their sizes differ.
function Compare-Pe([string]$a, [string]$b) {
    $x = Get-PeCodeBytes $a; $y = Get-PeCodeBytes $b
    if ($x.Length -ne $y.Length) { return -1 }
    if ((ConvertTo-Sha256Hex $x) -eq (ConvertTo-Sha256Hex $y)) { return 0 }
    $n = 0
    for ($i = 0; $i -lt $x.Length; $i++) { if ($x[$i] -ne $y[$i]) { $n++ } }
    return $n
}
# A copy of a PE file with the middle byte of its .text section inverted.
function Copy-Flipped([string]$from, [string]$to) { Copy-PeFlippedText $from $to }
# A copy of any file with its middle byte inverted.
function Copy-FlippedFile([string]$from, [string]$to) {
    $d = [IO.File]::ReadAllBytes($from)
    $i = [int]($d.Length / 2)
    $d[$i] = $d[$i] -bxor 0xFF
    [IO.File]::WriteAllBytes($to, $d)
    return $to
}
# The git blob id of a file's bytes, as `git hash-object --no-filters` gives it.
function Get-BlobId([string]$path) {
    $body = [IO.File]::ReadAllBytes($path)
    $head = [Text.Encoding]::ASCII.GetBytes("blob $($body.Length)`0")
    $sha1 = [Security.Cryptography.SHA1]::Create()
    return ([BitConverter]::ToString($sha1.ComputeHash([byte[]]($head + $body))) -replace '-', '').ToLower()
}
