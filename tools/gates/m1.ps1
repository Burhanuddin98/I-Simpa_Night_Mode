# Each says-NO input is a run that happened (an integer exit code): it is refused for what it
# produced, never because it failed to start.
function Ran($code) { $code -is [int] }
$sppsInputs = @('config.xml', 'mesh.cbin', 'tetramesh.mbin', 'expected.json')
function Invoke-Run([string]$exe, [string]$from, [string]$label, $edit) {
    Safe {
        $dir = New-RunFrom $from $label
        if ($edit) { Edit-Once (Join-Path $dir 'config.xml') $edit[0] $edit[1] }
        $code = Invoke-Solver $exe $dir @('config.xml')
        [pscustomobject]@{ Dir = $dir; Exit = $code; Out = (Get-Outputs $dir $sppsInputs); Sizes = (Get-Sizes $dir) }
    }
}
