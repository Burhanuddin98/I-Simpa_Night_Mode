# One exact text edit of a file, which must match exactly once.
function Edit-Once([string]$file, [string]$old, [string]$new) {
    $text = [IO.File]::ReadAllText($file)
    $n = ([regex]::Matches($text, [regex]::Escape($old))).Count
    if ($n -ne 1) { throw "edit of ${file}: '$old' matches $n times, not once" }
    [IO.File]::WriteAllText($file, $text.Replace($old, $new), (New-Object Text.UTF8Encoding $false))
}
# Runs an executable with a hard time limit. Returns its exit code, or 'TIMEOUT' (which no check
# accepts) after killing it.
function Invoke-Solver([string]$exe, [string]$dir, [string[]]$argv, [int]$limitSec = 300) {
    $p = Start-Process -FilePath $exe -ArgumentList $argv -WorkingDirectory $dir -NoNewWindow -PassThru `
        -RedirectStandardOutput (Join-Path $dir '_stdout.txt') -RedirectStandardError (Join-Path $dir '_stderr.txt')
    $null = $p.Handle   # keeps ExitCode readable once the process has ended
    if (-not $p.WaitForExit($limitSec * 1000)) {
        Stop-Process -Id $p.Id -Force -ErrorAction SilentlyContinue
        Write-Host "      | TIMEOUT: $exe in $dir ran over $limitSec s and was killed"
        return 'TIMEOUT'
    }
    $p.WaitForExit()
    return $p.ExitCode
}
function Get-Outputs([string]$dir, [string[]]$inputs) {
    $h = @{}
    Get-ChildItem $dir -Recurse -File |
        Where-Object { $_.Name -notin $inputs -and $_.Name -notlike '_std*.txt' } |
        ForEach-Object { $h[$_.FullName.Substring($dir.Length + 1)] = (Get-FileHash $_.FullName -Algorithm SHA256).Hash }
    return $h
}
function Compare-Outputs($a, $b) {
    $keys = @($a.Keys) + @($b.Keys) | Sort-Object -Unique
    return @($keys | Where-Object { $a[$_] -ne $b[$_] })
}
# .csbin (RSBIN surface receivers) is written by dumping whole C structs, padding included, so two
# runs of the SAME executable differ in 2 bytes per 8-byte record (verified 2026-09-23). Bytes are
# meaningless there; M1 checks the same files at the same sizes, and M2 compares them decoded.
function Get-Sizes([string]$dir) {
    $h = @{}
    Get-ChildItem $dir -Recurse -File -Filter *.csbin | ForEach-Object { $h[$_.FullName.Substring($dir.Length + 1)] = $_.Length }
    return $h
}
function Get-Sha([string]$path) { (Get-FileHash -LiteralPath $path -Algorithm SHA256).Hash.ToLower() }

# A PE32+ file's bytes with its link timestamps zeroed: the COFF header's TimeDateStamp and each
# debug-directory entry's. Returns the section table too.
function Read-MaskedPe([string]$path) {
    $d = [IO.File]::ReadAllBytes($path)
    $pe = [BitConverter]::ToInt32($d, 0x3C)
    if ([BitConverter]::ToUInt32($d, $pe) -ne 0x4550) { throw "$path is not a PE file" }
    $coff = $pe + 4
    $nsec = [BitConverter]::ToUInt16($d, $coff + 2)
    $optSize = [BitConverter]::ToUInt16($d, $coff + 16)
    $opt = $coff + 20
    if ([BitConverter]::ToUInt16($d, $opt) -ne 0x20B) { throw "$path is not PE32+" }
    [Array]::Clear($d, $coff + 4, 4)
    $dbgRva = [BitConverter]::ToUInt32($d, $opt + 112 + 48)
    $dbgSize = [BitConverter]::ToUInt32($d, $opt + 112 + 52)
    $sections = @()
    for ($i = 0; $i -lt $nsec; $i++) {
        $s = $opt + $optSize + 40 * $i
        $sec = [pscustomobject]@{
            Name = [Text.Encoding]::ASCII.GetString($d, $s, 8).TrimEnd([char]0)
            VSize = [BitConverter]::ToUInt32($d, $s + 8); Va = [BitConverter]::ToUInt32($d, $s + 12)
            RSize = [BitConverter]::ToUInt32($d, $s + 16); RPtr = [BitConverter]::ToUInt32($d, $s + 20)
        }
        $sections += $sec
        if ($dbgSize -gt 0 -and $dbgRva -ge $sec.Va -and $dbgRva -lt $sec.Va + $sec.VSize) {
            $off = $sec.RPtr + ($dbgRva - $sec.Va)
            for ($k = 0; $k -lt [int][math]::Floor($dbgSize / 28); $k++) { [Array]::Clear($d, $off + 28 * $k + 4, 4) }
        }
    }
    [pscustomobject]@{ Bytes = $d; Sections = $sections }
}
# How many bytes two PE files differ in outside their link timestamps; -1 when their sizes differ.
function Compare-Pe([string]$a, [string]$b) {
    $x = (Read-MaskedPe $a).Bytes; $y = (Read-MaskedPe $b).Bytes
    if ($x.Length -ne $y.Length) { return -1 }
    $sha = [Security.Cryptography.SHA256]::Create()
    if ([BitConverter]::ToString($sha.ComputeHash($x)) -eq [BitConverter]::ToString($sha.ComputeHash($y))) { return 0 }
    $n = 0
    for ($i = 0; $i -lt $x.Length; $i++) { if ($x[$i] -ne $y[$i]) { $n++ } }
    return $n
}
# A copy of a PE file with the middle byte of its .text section inverted.
function Copy-Flipped([string]$from, [string]$to) {
    $text = (Read-MaskedPe $from).Sections | Where-Object { $_.Name -eq '.text' }
    $d = [IO.File]::ReadAllBytes($from)
    $i = $text.RPtr + [int]($text.RSize / 2)
    $d[$i] = $d[$i] -bxor 0xFF
    [IO.File]::WriteAllBytes($to, $d)
    return $to
}
# The git blob id of a file's bytes, as `git hash-object --no-filters` gives it.
function Get-BlobId([string]$path) {
    $body = [IO.File]::ReadAllBytes($path)
    $head = [Text.Encoding]::ASCII.GetBytes("blob $($body.Length)`0")
    $sha1 = [Security.Cryptography.SHA1]::Create()
    return ([BitConverter]::ToString($sha1.ComputeHash([byte[]]($head + $body))) -replace '-', '').ToLower()
}
# The files of a folder whose blob ids are not upstream 4db335c's; empty when all match.
function Get-BlobMismatches([string]$dir) {
    @($blobs4db.Keys | Where-Object { -not (Test-Path -LiteralPath (Join-Path $dir $_)) -or (Get-BlobId (Join-Path $dir $_)) -ne $blobs4db[$_] })
}
# SHA256SUMS of the committed tree, as an ordered map name -> sha256.
function Read-Sums {
    $m = [ordered]@{}
    foreach ($line in Get-Content (Join-Path $tgSrc 'SHA256SUMS')) {
        if ($line -notmatch '^([0-9a-f]{64})  (\S+)$') { throw "SHA256SUMS: unreadable line '$line'" }
        $m[$Matches[2]] = $Matches[1]
    }
    return $m
}
# The files SHA256SUMS lists that a folder lacks or holds with other bytes; empty when it holds
# all of them unchanged.
function Get-SumMismatches([string]$dir) {
    $sums = Read-Sums
    if ($sums.Count -ne 8) { throw "SHA256SUMS lists $($sums.Count) files, not the tarball's 8" }
    @($sums.Keys | Where-Object { -not (Test-Path -LiteralPath (Join-Path $dir $_)) -or (Get-Sha (Join-Path $dir $_)) -ne $sums[$_] })
}
# Whether a solver manifest records this build: the pinned commit, TetGen 1.5.0 from the WIAS
# tarball with upstream 4db335c's blobs, the vendored files' hashes, and the shipped tetgen's hash.
function Test-Manifest($m) {
    $t = $m.tetgen
    if ($null -eq $t -or $null -eq $t.files_sha256) { return $false }
    $sums = Read-Sums
    $listed = @($t.files_sha256.PSObject.Properties)
    $filesOk = ($listed.Count -eq $sums.Count) -and (@($sums.Keys | Where-Object { $t.files_sha256.$_ -ne $sums[$_] }).Count -eq 0)
    return ($m.upstream_commit -eq $commit) -and ($t.version -eq '1.5.0') -and ($t.tarball_sha256 -eq $tarballSha) -and
        ($t.same_blobs_as_upstream -eq $blobCommit) -and $filesOk -and ($t.exe_sha256 -eq $m.sha256.'tetgen.exe')
}
