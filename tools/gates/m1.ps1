# Our records with one compile flag edited, read through the same comparison.
function Get-MutatedDiff([string]$label, [string]$old, [string]$new) {
    $mutTlog = Join-Path $no "tetgen.tlog-$label"
    New-Item -ItemType Directory -Force $mutTlog | Out-Null
    Copy-Item (Join-Path $tgBld 'tetgen.dir\Release\tetgen.tlog\*') $mutTlog
    $clLog = Join-Path $mutTlog 'CL.command.1.tlog'
    $text = [IO.File]::ReadAllText($clLog)
    if (([regex]::Matches($text, [regex]::Escape($old))).Count -ne 2) { throw "'$old' is not in both compile records" }
    [IO.File]::WriteAllText($clLog, $text.Replace($old, $new), [Text.Encoding]::Unicode)
    Compare-BuildCommands $refCmds (Get-BuildCommands $tgBld $tgSrc $mutTlog)
}
function Test-BothCompilesDiffer($d, [string]$flag) {
    ($d.Count -eq 4) -and (@($d | Where-Object { $_.StartsWith('> CL') -and $_.Contains($flag) }).Count -eq 2)
}
