function Test-SppsBanner($r) { (Get-Content (Join-Path $r.Dir '_stdout.txt') -TotalCount 1) -match '^SPPS version 2\.2\.1' }
function Test-End($r) { Select-String -Path (Join-Path $r.Dir '_stdout.txt') -Pattern '^End of calculation' -Quiet }
function Test-Produced($a, $b) { ($a.Out.Count -gt 0) -and ($b.Out.Count -eq $a.Out.Count) }
function Get-StatDiff($diff) { @($diff | Where-Object { $_ -like '*.recp' -or $_ -like '*particle statistics.gabe' }) }
function Get-NonCsbin($diff) { @($diff | Where-Object { $_ -notlike '*.csbin' }) }
function Test-SameSizes($a, $b) { @(Compare-Outputs $a.Sizes $b.Sizes).Count -eq 0 }

