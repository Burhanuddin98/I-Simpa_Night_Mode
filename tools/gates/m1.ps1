# A tutorial's 2019 temp folder, read out of upstream's tutorial_<n>.proj (a zip) at gate time:
# the .poly (and .var) upstream's GUI gave TetGen, and the .1.* files TetGen gave back.
function Get-Tutorial2019([int]$n) {
    $dir = Join-Path $work "tut$n-2019"
    New-Item -ItemType Directory -Force $dir | Out-Null
    $proj = Join-Path $up "src\isimpa\resources\doc\tutorial\tutorial $n\tutorial_$n.proj"
    $zip = [IO.Compression.ZipFile]::OpenRead($proj)
    try {
        $temp = @($zip.Entries | Where-Object { $_.FullName -match '^instance\d+/temp/[^/]+$' })
        $inst = @($temp | ForEach-Object { $_.FullName.Split('/')[0] } | Sort-Object -Unique)
        if ($inst.Count -ne 1) { throw "tutorial_$n.proj has temp files under $($inst.Count) instances, not 1" }
        foreach ($e in $temp) { [IO.Compression.ZipFileExtensions]::ExtractToFile($e, (Join-Path $dir $e.Name), $true) }
    } finally { $zip.Dispose() }
    return $dir
}
