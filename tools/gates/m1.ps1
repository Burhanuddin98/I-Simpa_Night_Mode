# A file's lines as bytes (Latin-1, one char per byte), terminators kept.
function Read-Lines([string]$path) {
    $text = [Text.Encoding]::GetEncoding(28591).GetString([IO.File]::ReadAllBytes($path))
    return @([regex]::Split($text, '(?<=\n)') | Where-Object { $_.Length -gt 0 })
}
# TetGen outputs against the 2019 tutorial files: every byte equal except the one
# '# Generated by' line each file ends with, which names the exe and input path.
function Compare-TetgenOutputs([string]$runDir, [string]$refDir) {
    $res = [ordered]@{}
    foreach ($ext in 'node', 'ele', 'face', 'neigh', 'edge') {
        $a = Join-Path $runDir "scene_mesh.1.$ext"; $b = Join-Path $refDir "scene_mesh.1.$ext"
        if (-not (Test-Path $a)) { $res[$ext] = 'missing'; continue }
        $la = Read-Lines $a; $lb = Read-Lines $b
        $ta = @($la | Where-Object { $_.StartsWith('# Generated by') }); $tb = @($lb | Where-Object { $_.StartsWith('# Generated by') })
        $ba = -join @($la | Where-Object { -not $_.StartsWith('# Generated by') })
        $bb = -join @($lb | Where-Object { -not $_.StartsWith('# Generated by') })
        $res[$ext] = if ($ta.Count -ne 1 -or $tb.Count -ne 1) { "trailer lines $($ta.Count)/$($tb.Count), not 1/1" }
                     elseif ($ba.Length -eq 0) { 'empty' }
                     elseif ($ba -ceq $bb) { 'identical' } else { 'differs' }
    }
    return $res
}
