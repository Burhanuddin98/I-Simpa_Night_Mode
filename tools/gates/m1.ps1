# A checkout's changed tracked files, one porcelain line each. A git failure is a line too, so a
# folder git cannot read never passes for a clean one.
function Get-TrackedChanges([string]$path) {
    $ErrorActionPreference = 'Continue'
    $out = @(& git -C $path status --porcelain --untracked-files=no 2>&1 | ForEach-Object { "$_" })
    if ($LASTEXITCODE -ne 0) { return @("git status exited $LASTEXITCODE") + $out }
    return $out
}
# A checkout's HEAD commit, or a 'no HEAD' text when git cannot name one.
function Get-Head([string]$path) {
    $ErrorActionPreference = 'Continue'
    $h = @(& git -C $path rev-parse --verify -q HEAD 2>$null)
    if ($LASTEXITCODE -ne 0 -or $h.Count -ne 1) { return "no HEAD (git exit $LASTEXITCODE)" }
    return "$($h[0])"
}
