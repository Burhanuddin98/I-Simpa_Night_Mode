/// How far two runs' numbers are apart, over every file both wrote: `(values that differ, largest
/// absolute difference, largest relative difference)`. GABE float columns and `.csbin` energies
/// are compared value by value; a file that does not decode counts as one difference of NaN.
/// How far two runs' numbers are apart, over every file both wrote. GABE float columns and `.csbin`
/// energies are compared value by value, per file; a file that does not decode counts as one
/// difference of NaN.
#[derive(Debug, Default)]
struct Spread {
    /// Values whose bits differ.
    n: usize,
    /// Of those, values that differ other than by a NaN's sign.
    numeric: usize,
    /// The largest absolute difference.
    abs: f64,
    /// The largest relative difference among values at least 1e-3 of their file's largest
    /// magnitude (the rest, near-zero intensity components, give meaningless ratios).
    rel: f64,
}

impl Spread {
    fn file(&mut self, pairs: &[(f32, f32)]) {
        let top = pairs
            .iter()
            .flat_map(|&(a, b)| [a, b])
            .filter(|v| v.is_finite())
            .fold(0f32, |m, v| m.max(v.abs()));
        for &(a, b) in pairs {
            if a.to_bits() == b.to_bits() {
                continue;
            }
            self.n += 1;
            if a.is_nan() && b.is_nan() {
                continue;
            }
            self.numeric += 1;
            let (a, b) = (f64::from(a), f64::from(b));
            let d = (a - b).abs();
            self.abs = self.abs.max(d);
            let m = a.abs().max(b.abs());
            if m >= 1e-3 * f64::from(top) && m > 0.0 {
                self.rel = self.rel.max(d / m);
            }
        }
    }
}

fn value_spread(theirs: &Outputs, ours: &Outputs) -> Spread {
    let mut s = Spread::default();
    for (k, t) in theirs {
        let Some(o) = ours.get(k) else { continue };
        if t == o {
            continue;
        }
        let mut pairs = Vec::new();
        if k.ends_with(".csbin") {
            if let (Ok(t), Ok(o)) = (csbin::read(t), csbin::read(o)) {
                for (rt, ro) in t.receivers.iter().zip(&o.receivers) {
                    for (ft, fo) in rt.faces.iter().zip(&ro.faces) {
                        for (a, b) in ft.records.iter().zip(fo.records.iter()) {
                            pairs.push((a.energy, b.energy));
                        }
                    }
                }
                s.file(&pairs);
                continue;
            }
        } else if let (Ok(t), Ok(o)) = (gabe::read(t), gabe::read(o)) {
            for (ct, co) in t.columns.iter().zip(&o.columns) {
                if let (
                    gabe::ColumnData::Float { values: vt, .. },
                    gabe::ColumnData::Float { values: vo, .. },
                ) = (&ct.data, &co.data)
                {
                    pairs.extend(vt.iter().copied().zip(vo.iter().copied()));
                }
            }
            s.file(&pairs);
            continue;
        }
        s.n += 1;
        s.numeric += 1;
        s.abs = f64::NAN;
    }
    s
}

/// Upstream's shipped solvers against ours, on tutorial 1's original inputs with the bed's edits
/// (seed 1, 10,000 particles, 500, 1000 and 2000 Hz): SPPS and TCR of v1.3.4 (2020-12-23, the last
/// stable release) and of v1.4.0 (2026-01-14, the pinned 929a5c8, whose sources ours are built
/// from). `$SIMPA_RELEASE_BINARIES` names the folder holding the installed releases,
/// `inst134\core\{spps,classical_theory}\` and `inst140\`: upstream's installers are not in this
/// repository, so this test is ignored in the plain suite and run by `tools/gates/parity.ps1`,
/// which passes the folder. It panics when the variable or a solver is missing.
///
/// The measured answer is in `docs/m5-m6-design.md`, decision 3.
#[test]
#[ignore = "needs upstream's installed 1.3.4 and 1.4.0 releases: tools/gates/parity.ps1 runs it with SIMPA_RELEASE_BINARIES"]
fn shipped_1_3_4_and_1_4_0_solvers_against_ours() {
    let root = std::env::var_os("SIMPA_RELEASE_BINARIES")
        .map(PathBuf::from)
        .expect("SIMPA_RELEASE_BINARIES must name the folder holding inst134 and inst140");
    let exe = |p: &str| {
        let p = root.join(p);
        assert!(p.is_file(), "{} is missing", p.display());
        p
    };
    let t = tutorial(parity::TUTORIAL1);
    let mut summary = Vec::new();
    for (kind, ours, v140, v134) in [
        (
            SolverKind::Spps,
            solver_exe("spps.exe"),
            exe("inst140/spps.exe"),
            exe("inst134/core/spps/spps.exe"),
        ),
        (
            SolverKind::Tcr,
            solver_exe("classicalTheory.exe"),
            exe("inst140/classicalTheory.exe"),
            exe("inst134/core/classical_theory/classicalTheory.exe"),
        ),
    ] {
        let r = t.runs.iter().find(|r| r.solver == kind).unwrap();
        let config = short_run(&r.config, kind);
        let name = solver_name(kind);
        let dir = bed_dir(&format!("shipped-{name}"));
        let mut runs: Vec<(&str, Outputs)> = Vec::new();
        for (label, program) in [("ours", &ours), ("1.4.0", &v140), ("1.3.4", &v134)] {
            let d = dir.join(label.replace('.', ""));
            std::fs::create_dir_all(&d).unwrap();
            let wd = simpa_core::config_xml::working_directory(&d).unwrap();
            std::fs::write(
                d.join("config.xml"),
                edit_attr(&config, "<configuration ", "workingdirectory", &wd),
            )
            .unwrap();
            std::fs::write(d.join("mesh.cbin"), &r.mesh_bytes).unwrap();
            std::fs::write(d.join("tetramesh.mbin"), &r.tetra_bytes).unwrap();
            let run = parity::support::run_solver(program, &d);
            println!(
                "{name} {label} ({}): exit {:?}",
                program.display(),
                run.exit
            );
            assert_eq!(
                run.exit,
                Some(0),
                "{name} {label}: {}\n{}",
                run.stdout,
                run.stderr
            );
            runs.push((
                label,
                parity::support::outputs(&d, &["config.xml", "mesh.cbin", "tetramesh.mbin"]),
            ));
        }
        for (a, b) in [(0, 1), (0, 2), (1, 2)] {
            let (la, oa) = &runs[a];
            let (lb, ob) = &runs[b];
            let d = output_differences(ob, oa, &BTreeMap::new());
            let s = value_spread(ob, oa);
            let same: Vec<&String> = oa.keys().filter(|k| oa.get(*k) == ob.get(*k)).collect();
            let line = format!(
                "{name}: {la} against {lb}: {} of {} files differ; {} values differ ({} other than \
                 by a NaN's sign), largest {:e} absolute, {:e} relative (values at least 1e-3 of \
                 their file's largest){}; identical: {same:?}",
                d.len(),
                oa.len().max(ob.len()),
                s.n,
                s.numeric,
                s.abs,
                s.rel,
                if d.is_empty() {
                    String::new()
                } else {
                    format!("; first: {}", d[0])
                }
            );
            println!("{line}");
            for x in &d {
                println!("    {x}");
            }
            // Per file: how far apart, and for a surface receiver also each face's energy summed
            // over its time steps.
            for (k, t) in ob
                .iter()
                .filter(|(k, t)| oa.get(*k).is_some_and(|o| o != *t))
            {
                let one = BTreeMap::from([(k.clone(), t.clone())]);
                let other = BTreeMap::from([(k.clone(), oa[k].clone())]);
                let s = value_spread(&one, &other);
                let mut per_face = String::new();
                if k.ends_with(".csbin")
                    && let (Ok(x), Ok(y)) = (csbin::read(t), csbin::read(&oa[k]))
                {
                    let mut worst = 0f64;
                    for (rx, ry) in x.receivers.iter().zip(&y.receivers) {
                        for (fx, fy) in rx.faces.iter().zip(&ry.faces) {
                            let sx: f64 = fx.records.iter().map(|r| f64::from(r.energy)).sum();
                            let sy: f64 = fy.records.iter().map(|r| f64::from(r.energy)).sum();
                            let m = sx.abs().max(sy.abs());
                            if m > 0.0 {
                                worst = worst.max((sx - sy).abs() / m);
                            }
                        }
                    }
                    per_face = format!("; each face's energy summed over time: {worst:e} relative");
                }
                println!(
                    "      {k}: {} values differ, largest {:e} relative{per_face}",
                    s.n, s.rel
                );
            }
            summary.push(line);
            if (a, b) == (0, 1) {
                // Ours is the pinned 929a5c8 sources built as upstream builds them: bit for bit.
                assert_eq!(
                    d,
                    Vec::<String>::new(),
                    "{name}: ours against the shipped 1.4.0"
                );
            } else {
                // 1.3.4 is another build of other sources: it must differ, or this bed cannot tell
                // two builds apart. How much is measured and reported.
                assert!(!d.is_empty(), "{name}: {la} against {lb}: bit-identical");
            }
        }
    }
    println!("\n{}", summary.join("\n"));
}
