/// A new folder under `<repo>/target/parity-bed/`, short enough that the deepest solver output
/// stays well under Windows' 260-character path limit (a longer path is skipped by the solvers
/// with exit 0 and no message, `config_xml_solver.rs`). Never reused, never deleted.
fn bed_dir(label: &str) -> PathBuf {
    static N: AtomicUsize = AtomicUsize::new(0);
    let dir = support::paths::repo_root()
        .join("target/parity-bed")
        .join(format!(
            "{}-{}-{label}",
            std::process::id(),
            N.fetch_add(1, Ordering::SeqCst)
        ));
    std::fs::create_dir_all(&dir).unwrap();
    let deepest = dir.as_os_str().len()
        + "/Punctual receivers/Receiver 1/Punctual receiver intensity.gabe".len();
    assert!(deepest < 240, "{} is too deep for MAX_PATH", dir.display());
    dir
}

/// `simpa import-proj <tutorial> <dir>/project.simpa`: must exit 0.
fn import_proj(rel: &str, dir: &Path) -> PathBuf {
    let proj = support::paths::upstream_file(rel);
    let out = dir.join("project.simpa");
    let o = simpa_run(&[
        "import-proj".to_string(),
        proj.display().to_string(),
        out.display().to_string(),
    ]);
    assert_eq!(o.code, 0, "import-proj {rel}: {o:#?}");
    out
}

/// `simpa mesh <project> --out <dir> --json`: must exit 0 with status OK.
fn mesh(project: &Path, out: &Path) -> Value {
    let o = simpa_run(&[
        "mesh".to_string(),
        project.display().to_string(),
        "--out".into(),
        out.display().to_string(),
        "--json".into(),
    ]);
    assert_eq!(o.code, 0, "simpa mesh {}: {o:#?}", project.display());
    let m = json(&o);
    assert_eq!(m["status"], "OK", "{m:#}");
    m
}

/// `simpa export-config <project> <dir> --solver <kind>`: our `config.xml` and `mesh.cbin`.
fn export_config(project: &Path, dir: &Path, kind: SolverKind) -> (String, Vec<u8>) {
    let o = simpa_run(&[
        "export-config".to_string(),
        project.display().to_string(),
        dir.display().to_string(),
        "--solver".into(),
        solver_name(kind).into(),
    ]);
    assert_eq!(o.code, 0, "export-config: {o:#?}");
    (
        std::fs::read_to_string(dir.join("config.xml")).unwrap(),
        std::fs::read(dir.join("mesh.cbin")).unwrap(),
    )
}

fn solver_name(kind: SolverKind) -> &'static str {
    match kind {
        SolverKind::Spps => "spps",
        SolverKind::Tcr => "tcr",
    }
}

