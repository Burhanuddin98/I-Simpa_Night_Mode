//! The parity bed (`docs/m5-m6-design.md`, decision 3): our build against original I-Simpa on
//! upstream's three tutorials, from the `.proj` to the solvers' results.
//!
//! For each tutorial, through the built `simpa` as a user drives it:
//! 1. **Import** the `.proj` with `simpa import-proj`.
//! 2. **Mesh** it with `simpa mesh` (TetGen 1.5.0, the M1 build found through `common/paths.rs`:
//!    `$SIMPA_SOLVERS_DIR`, else the dev tree; a missing build panics, nothing skips).
//! 3. **Compare our inputs with the files original I-Simpa wrote** into the `.proj`: `.poly` and
//!    `.var` byte for byte; TetGen's `.1.{node,ele,face,neigh,edge}` byte for byte, the trailer
//!    (`# Generated by ...`, which names the program and folder) excluded (for tutorial 2, the
//!    `.poly` and `.node` lines printed at decimal ties are counted and pinned, their values
//!    equal: [`TUTORIAL2_TIES`]); the `.mbin` byte for byte, `idVolume` included (both sides write
//!    TetGen's region attribute unchanged, decision 1; where a tutorial has fitting zones, their
//!    seeds are upstream's GUI session ids on its side and the project's on ours, so its ids are
//!    read through the map TetGen's numbering gives, [`volume_ids`]); `mesh.cbin` and `config.xml`
//!    as `crates/simpa-core/tests/parity_inputs.rs` defines equality (what the solver reads, value
//!    by value, with the ids and the listed differences by design), the helpers shared through
//!    `parity_support.rs`.
//! 4. **Run SPPS and TCR** (our M1 builds of upstream's 929a5c8 sources) on our inputs and on the
//!    original inputs, both edited alike: `random_seed` 1, 10,000 particles, and at most three
//!    computed bands (500, 1000 and 2000 Hz where a run computes more). Every output file must be
//!    the same: `.csbin` compared decoded (its struct padding is not deterministic, M1) with the
//!    surface receivers' `xmlIndex` read through the id map, every other file byte for byte, which
//!    makes `.gabe` and `.recp` values bit-exact. A difference names the file and its first
//!    differing value, from the canonical dump. The one difference allowed is named with its
//!    cause and proven: tutorial 1's two `Advanced sound level.gap`, from the receiver directions
//!    a `.proj` stores with 6 digits, which match once our config carries the run's own. It is
//!    not a difference from what original I-Simpa writes from this `.proj`: its GUI saves a
//!    direction with `ostream`'s default 6 digits (`e_data_float.h:163, 249-257`), reads that
//!    text back on load (`:65-66`), and recomputes a direction only when a position is edited, never
//!    on load (`e_scene_recepteursp_recepteur.h:63, 105, 195-219`); the runs were written in the
//!    2019 session, before the save ([`directions_of`]).
//!
//! What each tutorial holds decides what can be compared (`parity_inputs.rs::what_the_tutorials_hold`):
//! - **tutorial 1**: TetGen's files under `temp/` and two run folders (SPPS, TCR): everything;
//! - **tutorial 2**: TetGen's files under `temp/` (no `.var`: its project constrains no surface) and
//!   no run folder: the mesher's inputs and outputs only. There is no original `.mbin`, `.cbin`,
//!   `config.xml` or result to compare with;
//! - **tutorial 3**: TetGen's files under `temp/` and three SPPS run folders. `simpa import-proj`
//!   reads it, fitting zones, per-band laws and transmission and source groups included, and
//!   records upstream's element ids beside the entities they became; each run's `config.xml` and
//!   `mesh.cbin` are compared with ours from the `.proj` read with that run's saved project,
//!   upstream's ids read through that recorded map (Burhan's open decision 1). `simpa mesh`
//!   refuses the project: TetGen stops on the box standing on the floor, which upstream took
//!   through `preprocess.exe` (not built), so what follows upstream's own `.poly` is compared: our
//!   TetGen, our builder, and the runs ([`tutorial_3_same_seed_runs`]).
//!
//! Every comparison has a refusal beside it, the input that makes it say no
//! (`the_comparisons_say_no`).

