/// The same edits on the original's `config.xml` and ours: `parity::repeatable` (SPPS: seed 1,
/// 10,000 particles) and at most three computed bands, 500, 1000 and 2000 Hz, when the config
/// computes more.
fn short_run(config: &str, kind: SolverKind) -> String {
    let text = parity::repeatable(config, kind);
    let doc = roxmltree::Document::parse(&text).unwrap();
    let computed: Vec<String> = doc
        .descendants()
        .filter(|n| {
            n.has_tag_name("bfreq") && n.parent().is_some_and(|p| p.has_tag_name("freq_enum"))
        })
        .filter(|n| n.attribute("docalc") == Some("1"))
        .map(|n| n.attribute("freq").unwrap().to_string())
        .collect();
    drop(doc);
    if computed.len() <= 3 {
        return text;
    }
    let keep = ["500", "1000", "2000"];
    assert!(
        keep.iter().all(|f| computed.iter().any(|c| c == f)),
        "{computed:?}"
    );
    let mut out = text;
    for f in computed.iter().filter(|f| !keep.contains(&f.as_str())) {
        let from = format!("<bfreq freq=\"{f}\" docalc=\"1\"/>");
        let to = format!("<bfreq freq=\"{f}\" docalc=\"0\"/>");
        assert_eq!(out.matches(&from).count(), 1, "{from}");
        out = out.replace(&from, &to);
    }
    out
}

/// Runs `kind` (our M1 build) in the new folder `dir` on `config` (its working directory set to
/// that folder), the scene mesh `cbin` and the tetrahedral mesh `mbin`. It must exit 0 and print
/// its completion line. Returns its output files.
fn run(dir: &Path, kind: SolverKind, config: &str, cbin: &[u8], mbin: &[u8]) -> Outputs {
    std::fs::create_dir_all(dir).unwrap();
    let wd = simpa_core::config_xml::working_directory(dir).unwrap();
    let text = edit_attr(config, "<configuration ", "workingdirectory", &wd);
    std::fs::write(dir.join("config.xml"), text).unwrap();
    std::fs::write(dir.join("mesh.cbin"), cbin).unwrap();
    std::fs::write(dir.join("tetramesh.mbin"), mbin).unwrap();
    let exe = solver_exe(match kind {
        SolverKind::Spps => "spps.exe",
        SolverKind::Tcr => "classicalTheory.exe",
    });
    let r = parity::support::run_solver(&exe, dir);
    assert_eq!(r.exit, Some(0), "{}: {}", dir.display(), r.stderr);
    let done = match kind {
        SolverKind::Spps => "End of calculation.",
        SolverKind::Tcr => "Step 3/3",
    };
    assert!(r.has_line(done), "{}:\n{}", dir.display(), r.stdout);
    parity::support::outputs(dir, &["config.xml", "mesh.cbin", "tetramesh.mbin"])
}

/// The original's run and ours on the same edits: the output differences, and how many files each
/// wrote. Their `.csbin` receiver ids are read through `rs_ids`.
#[allow(clippy::too_many_arguments)]
fn same_seed(
    label: &str,
    kind: SolverKind,
    original: (&str, &[u8], &[u8]),
    ours: (&str, &[u8], &[u8]),
    rs_ids: &BTreeMap<i32, i32>,
) -> (Outputs, Vec<String>) {
    let root = bed_dir(label);
    let theirs = run(
        &root.join("original"),
        kind,
        &short_run(original.0, kind),
        original.1,
        original.2,
    );
    let mine = run(
        &root.join("ours"),
        kind,
        &short_run(ours.0, kind),
        ours.1,
        ours.2,
    );
    assert!(
        !theirs.is_empty(),
        "{label}: the original's run wrote nothing"
    );
    let d = output_differences(&theirs, &mine, rs_ids);
    println!(
        "{label}: {} output files from the original's inputs, {} from ours; {} differ{}",
        theirs.len(),
        mine.len(),
        d.len(),
        if d.is_empty() {
            String::new()
        } else {
            format!(":\n  {}", d.join("\n  "))
        }
    );
    (theirs, d)
}

