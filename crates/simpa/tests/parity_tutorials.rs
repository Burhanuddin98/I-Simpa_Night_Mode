/// Our `.mbin` for tutorial 3's run `r` and our `config`: [`Tutorial3::built`] with the fittings
/// under our ids, and the room's parts as `room` gives them.
fn tutorial3_mbin(
    built: &mbin::Mesh,
    r: &parity::Run,
    our_config: &str,
    room: impl Fn(i32) -> i32,
) -> (Vec<u8>, BTreeMap<i32, i32>) {
    let fittings = parity::id_map(&r.config, our_config, "encombrement");
    let mut ids = BTreeMap::new();
    let mut mesh = built.clone();
    for tet in &mut mesh.tetrahedra {
        let to = fittings
            .get(&tet.id_volume)
            .copied()
            .unwrap_or_else(|| room(tet.id_volume));
        ids.insert(tet.id_volume, to);
        tet.id_volume = to;
    }
    (mbin::write(&mesh), ids)
}

