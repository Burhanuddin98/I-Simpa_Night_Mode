/// `ours` with each point receiver's direction (`u`, `v`, `w`) replaced by `theirs`'s, receiver by
/// receiver in list order: the directions upstream's GUI held when it wrote the run, which its
/// project file keeps only to 6 significant digits.
fn directions_of(ours: &str, theirs: &str) -> String {
    let doc = roxmltree::Document::parse(theirs).unwrap();
    let stored: Vec<[String; 3]> = doc
        .descendants()
        .filter(|n| n.has_tag_name("recepteur_ponctuel"))
        .map(|n| ["u", "v", "w"].map(|a| n.attribute(a).unwrap().to_string()))
        .collect();
    let tag = "<recepteur_ponctuel ";
    assert_eq!(ours.matches(tag).count(), stored.len());
    let mut out = String::new();
    let mut rest = ours;
    for uvw in &stored {
        let at = rest.find(tag).unwrap();
        out.push_str(&rest[..at]);
        let end = at + rest[at..].find('>').unwrap() + 1;
        let mut element = rest[at..end].to_string();
        for (a, v) in ["u", "v", "w"].iter().zip(uvw) {
            element = edit_attr(&element, tag, a, v);
        }
        out.push_str(&element);
        rest = &rest[end..];
    }
    out.push_str(rest);
    out
}

