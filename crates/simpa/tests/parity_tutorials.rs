/// The TetGen output files a mesh folder holds.
const TETGEN_FILES: [&str; 5] = ["node", "ele", "face", "neigh", "edge"];

/// Lines of a tutorial's files that differ from ours in text only: a coordinate at an exact decimal
/// tie in the 17th significant digit, printed rounded to even by ours and up by the 2019 build
/// (see [`TUTORIAL2_TIES`]). `(.poly lines, .1.node lines)`.
type Ties = (usize, usize);

/// Our `name` against the original's, line by line: no line may differ in value, and exactly
/// `text_only` lines may differ in text. One line for the summary; panics otherwise, naming the
/// first line that differs.
fn compare_text(name: &str, ours: &[u8], theirs: &[u8], text_only: usize, label: &str) -> String {
    let d = tetgen_difference(ours, theirs);
    assert_eq!(d.value_lines, 0, "{label}: {name}: {:?}", d.first_value);
    assert_eq!(
        d.text_lines, text_only,
        "{label}: {name}: {} lines differ in text, {text_only} expected; first {:?}",
        d.text_lines, d.first_text
    );
    if d.text_lines == 0 {
        format!("{name}: byte-identical, trailer excluded")
    } else {
        format!(
            "{name}: {} lines differ in text only, every value equal as f64 (first {})",
            d.text_lines,
            d.first_text.unwrap()
        )
    }
}

/// Our mesh folder's `.poly`, `.var` and `.1.*` against a tutorial's `temp/`, with the lines
/// expected to differ in text only. Returns one line per file, for the summary; panics on any
/// other difference, naming it.
fn compare_mesher_files(t: &Tutorial, mesh_dir: &Path, ties: Ties, label: &str) -> Vec<String> {
    let mut report = Vec::new();
    let ours = |name: &str| {
        std::fs::read(mesh_dir.join(name)).unwrap_or_else(|e| panic!("{label}: {name}: {e}"))
    };
    // The .poly, which has no trailer: byte for byte but the ties.
    report.push(compare_text(
        "scene_mesh.poly",
        &ours("scene_mesh.poly"),
        &entry(t, "temp/scene_mesh.poly"),
        ties.0,
        label,
    ));
    if ties.0 == 0 {
        assert_eq!(
            byte_difference(&ours("scene_mesh.poly"), &entry(t, "temp/scene_mesh.poly")),
            None,
            "{label}: scene_mesh.poly"
        );
    }
    // The .var, byte for byte, or absent on both sides.
    let var_theirs = has_entry(t, "temp/scene_mesh.var");
    let var_ours = mesh_dir.join("scene_mesh.var").is_file();
    assert_eq!(var_ours, var_theirs, "{label}: a .var on one side only");
    if var_theirs {
        let var = byte_difference(&ours("scene_mesh.var"), &entry(t, "temp/scene_mesh.var"));
        assert_eq!(var, None, "{label}: scene_mesh.var");
        report.push("scene_mesh.var: byte-identical".to_string());
    } else {
        report.push("scene_mesh.var: none written, as the original wrote none".to_string());
    }
    // TetGen's output, trailer excluded.
    for ext in TETGEN_FILES {
        let name = format!("scene_mesh.1.{ext}");
        let text_only = if ext == "node" { ties.1 } else { 0 };
        report.push(compare_text(
            &name,
            &ours(&name),
            &entry(t, &format!("temp/{name}")),
            text_only,
            label,
        ));
    }
    report
}

/// The original's `idVolume` to ours, as TetGen numbers the regions of a `.poly` whose fitting
/// seeds carry our ids instead of the original's: a fitting maps through `fittings` (the
/// original's `encombrement@id` to ours), and each room part, numbered by TetGen from one above
/// the largest seed (`VolumeIds::tetgen`), keeps its place above ours (tutorial 3: 2084 to 2086
/// become 4 to 6; tutorial 1, without fittings: 1 stays 1). Both sides write the attribute
/// unchanged (decision 1), and the regions are the same, so this is our mesher's numbering.
fn volume_ids(theirs_mbin: &[u8], fittings: &BTreeMap<i32, i32>) -> BTreeMap<i32, i32> {
    let start = |ids: Vec<i32>| simpa_core::mesh::verify::VolumeIds::tetgen(ids).room;
    let (theirs_room, ours_room) = (
        start(fittings.keys().copied().collect()),
        start(fittings.values().copied().collect()),
    );
    let ids: BTreeSet<i32> = mbin::read(theirs_mbin)
        .unwrap()
        .tetrahedra
        .iter()
        .map(|t| t.id_volume)
        .collect();
    ids.into_iter()
        .map(|id| {
            let ours = match fittings.get(&id) {
                Some(&f) => f,
                None => {
                    assert!(
                        id >= theirs_room,
                        "idVolume {id} is neither a fitting's nor TetGen's room numbering"
                    );
                    id - theirs_room + ours_room
                }
            };
            (id, ours)
        })
        .collect()
}

fn print_report(label: &str, report: &[String]) {
    println!("{label}:");
    for r in report {
        println!("  {r}");
    }
}

