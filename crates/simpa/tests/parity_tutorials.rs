//! The parity bed (`docs/m5-m6-design.md`, decision 3): our build against original I-Simpa on
//! upstream's three tutorials, from the `.proj` to the solvers' results.
//!
//! For each tutorial, through the built `simpa` as a user drives it:
//! 1. **Import** the `.proj` with `simpa import-proj`.
//! 2. **Mesh** it with `simpa mesh` (TetGen 1.5.0, the M1 build found through `common/paths.rs`:
//!    `$SIMPA_SOLVERS_DIR`, else the dev tree; a missing build panics, nothing skips).
//! 3. **Compare our inputs with the files original I-Simpa wrote** into the `.proj`: `.poly` and
//!    `.var` byte for byte; TetGen's `.1.{node,ele,face,neigh,edge}` byte for byte, the trailer
//!    (`# Generated by ...`, which names the program and folder) excluded; the `.mbin` byte for
//!    byte once each tetrahedron's `idVolume` is read through the id map (upstream writes TetGen's
//!    region attribute, 1 for a room, and its GUI's session ids for fittings; we write 0 and the
//!    project's ids, decision 1); `mesh.cbin` and `config.xml` as `crates/simpa-core/tests/
//!    parity_inputs.rs` defines equality (what the solver reads, value by value, with the ids and
//!    the listed differences by design), the helpers shared through `parity_support.rs`.
//! 4. **Run SPPS and TCR** (our M1 builds of upstream's 929a5c8 sources) on our inputs and on the
//!    original inputs, both edited alike: `random_seed` 1, 10,000 particles, and at most three
//!    computed bands (500, 1000 and 2000 Hz where a run computes more). Every output file must be
//!    the same: `.csbin` compared decoded (its struct padding is not deterministic, M1) with the
//!    surface receivers' `xmlIndex` read through the id map, every other file byte for byte, which
//!    makes `.gabe` and `.recp` values bit-exact. A difference names the file and its first
//!    differing value, from the canonical dump.
//!
//! What each tutorial holds decides what can be compared (`parity_inputs.rs::what_the_tutorials_hold`):
//! - **tutorial 1**: TetGen's files under `temp/` and two run folders (SPPS, TCR): everything;
//! - **tutorial 2**: TetGen's files under `temp/` (no `.var`: its project constrains no surface) and
//!   no run folder: the mesher's inputs and outputs only. There is no original `.mbin`, `.cbin`,
//!   `config.xml` or result to compare with;
//! - **tutorial 3**: TetGen's files under `temp/` and three SPPS run folders, but `simpa
//!   import-proj` refuses it: a `.proj`'s fitting zones are not imported. Checked as a refusal; the
//!   project is then taken from each run's `config.xml` and `mesh.cbin` with the two edits a
//!   project needs (`parity::importable`), saved, and driven through the same CLI.
//!
//! Every comparison has a refusal beside it, the input that makes it say no
//! (`the_comparisons_say_no`).

