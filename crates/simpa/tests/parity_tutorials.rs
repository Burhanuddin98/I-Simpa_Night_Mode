/// The first difference between two files' bytes: `None` when they are equal.
fn byte_difference(ours: &[u8], theirs: &[u8]) -> Option<String> {
    if ours == theirs {
        return None;
    }
    let at = ours
        .iter()
        .zip(theirs)
        .position(|(a, b)| a != b)
        .unwrap_or(ours.len().min(theirs.len()));
    Some(format!(
        "{} bytes against the original's {}; first difference at byte {at}: ours {:?}, the \
         original's {:?}",
        ours.len(),
        theirs.len(),
        ours.get(at),
        theirs.get(at)
    ))
}

/// TetGen's `.1.*` files compared line by line, the trailer (`# Generated by ...`) excluded.
#[derive(Debug, Default)]
struct TetgenDiff {
    /// Lines whose text differs.
    text_lines: usize,
    /// Of those, lines whose values differ: a token that is not the same number (as `f64`) or not
    /// the same word, or a line one file lacks.
    value_lines: usize,
    /// The first line whose values differ.
    first_value: Option<String>,
    /// The first line whose text differs.
    first_text: Option<String>,
}

fn is_trailer(line: &str) -> bool {
    line.starts_with("# Generated by ")
}

fn tetgen_difference(ours: &[u8], theirs: &[u8]) -> TetgenDiff {
    let lines = |b: &[u8]| -> Vec<String> {
        String::from_utf8_lossy(b)
            .lines()
            .filter(|l| !is_trailer(l))
            .map(str::to_string)
            .collect()
    };
    let (o, t) = (lines(ours), lines(theirs));
    let mut d = TetgenDiff::default();
    let same_values = |a: &str, b: &str| {
        let (x, y): (Vec<&str>, Vec<&str>) = (
            a.split_whitespace().collect(),
            b.split_whitespace().collect(),
        );
        x.len() == y.len()
            && x.iter().zip(&y).all(|(p, q)| {
                p == q
                    || matches!((p.parse::<f64>(), q.parse::<f64>()), (Ok(u), Ok(v)) if u.to_bits() == v.to_bits())
            })
    };
    for k in 0..o.len().max(t.len()) {
        let (a, b) = (o.get(k), t.get(k));
        if a == b {
            continue;
        }
        d.text_lines += 1;
        let line = format!(
            "line {}: ours {:?}, the original's {:?}",
            k + 1,
            a.map(String::as_str).unwrap_or("(none)"),
            b.map(String::as_str).unwrap_or("(none)")
        );
        if d.first_text.is_none() {
            d.first_text = Some(line.clone());
        }
        let equal = matches!((a, b), (Some(a), Some(b)) if same_values(a, b));
        if !equal {
            d.value_lines += 1;
            if d.first_value.is_none() {
                d.first_value = Some(line);
            }
        }
    }
    d
}

/// Our `.mbin` against the original's, byte for byte, once each of the original's tetrahedra has
/// its `idVolume` read through `ids` (the original's id to ours; an id missing from the map is
/// left as it is, so it shows). The original is decoded and written again by our writer, which
/// must give back its exact bytes first.
fn mbin_difference(ours: &[u8], theirs: &[u8], ids: &BTreeMap<i32, i32>) -> Option<String> {
    let mut t = match mbin::read(theirs) {
        Ok(m) => m,
        Err(e) => return Some(format!("the original does not read: {e}")),
    };
    if mbin::write(&t) != theirs {
        return Some("the original does not survive a read and a write".to_string());
    }
    for tet in &mut t.tetrahedra {
        if let Some(&o) = ids.get(&tet.id_volume) {
            tet.id_volume = o;
        }
    }
    let mapped = mbin::write(&t);
    if mapped == ours {
        return None;
    }
    // Name the first differing value from the canonical dumps.
    let dump_ours = match mbin::read(ours) {
        Ok(m) => mbin::dump(&m),
        Err(e) => return Some(format!("ours does not read: {e}")),
    };
    Some(
        first_dump_difference(&dump_ours, &mbin::dump(&t))
            .unwrap_or_else(|| byte_difference(ours, &mapped).unwrap_or_default()),
    )
}

/// The first line where two canonical dumps differ.
fn first_dump_difference(ours: &str, theirs: &str) -> Option<String> {
    let (o, t): (Vec<&str>, Vec<&str>) = (ours.lines().collect(), theirs.lines().collect());
    (0..o.len().max(t.len())).find_map(|k| {
        let (a, b) = (o.get(k), t.get(k));
        (a != b).then(|| {
            format!(
                "dump line {}: ours `{}`, the original's `{}`",
                k + 1,
                a.unwrap_or(&"(none)"),
                b.unwrap_or(&"(none)")
            )
        })
    })
}

/// The output files of one run, by path relative to its folder.
type Outputs = BTreeMap<String, Vec<u8>>;

/// Every difference between the original's run and ours, one line per file: a file only one run
/// wrote, or the first value that differs. A `.csbin` is compared decoded, the original's
/// receivers' `xmlIndex` read through `rs_ids`; every other file byte for byte, its first
/// differing value named from the GABE dump when it reads as one.
fn output_differences(
    theirs: &Outputs,
    ours: &Outputs,
    rs_ids: &BTreeMap<i32, i32>,
) -> Vec<String> {
    let mut out = Vec::new();
    for k in theirs.keys().filter(|k| !ours.contains_key(*k)) {
        out.push(format!("{k}: only the original's run wrote it"));
    }
    for k in ours.keys().filter(|k| !theirs.contains_key(*k)) {
        out.push(format!("{k}: only our run wrote it"));
    }
    for (k, t) in theirs {
        let Some(o) = ours.get(k) else { continue };
        let found = if k.ends_with(".csbin") {
            match (csbin::read(t), csbin::read(o)) {
                (Ok(t), Ok(o)) => csbin_difference(t, &o, rs_ids),
                (t, o) => Some(format!(
                    "does not decode: original {:?}, ours {:?}",
                    t.err(),
                    o.err()
                )),
            }
        } else if t == o {
            None
        } else {
            match (gabe::read(t), gabe::read(o)) {
                (Ok(t), Ok(o)) => first_dump_difference(&gabe::dump(&o), &gabe::dump(&t)),
                _ => byte_difference(o, t),
            }
            .or_else(|| byte_difference(o, t))
        };
        if let Some(d) = found {
            out.push(format!("{k}: {d}"));
        }
    }
    out.sort();
    out
}

/// Two decoded `.csbin`, the original's receivers' `xmlIndex` read through `rs_ids` first: the
/// first line where their canonical dumps differ (every value in hexadecimal, so bit for bit).
fn csbin_difference(
    mut theirs: csbin::Csbin,
    ours: &csbin::Csbin,
    rs_ids: &BTreeMap<i32, i32>,
) -> Option<String> {
    for r in &mut theirs.receivers {
        r.xml_index = *rs_ids.get(&r.xml_index).unwrap_or(&r.xml_index);
    }
    first_dump_difference(&csbin::dump(ours), &csbin::dump(&theirs))
}

