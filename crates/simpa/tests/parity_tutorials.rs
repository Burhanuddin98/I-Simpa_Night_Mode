/// How far two runs' numbers are apart, over every file both wrote. GABE float columns and `.csbin`
/// energies are compared value by value, per file; a file that does not decode counts as one
/// difference of NaN.
#[derive(Debug, Default)]
struct Spread {
    /// Values whose bits differ.
    n: usize,
    /// Of those, values that differ other than by a NaN's sign.
    numeric: usize,
    /// The largest absolute difference.
    abs: f64,
    /// The largest relative difference `|a - b| / max(|a|, |b|)` over every differing pair (a
    /// value against 0 counts 1).
    rel_all: f64,
    /// The same among values at least 1e-3 of their file's largest magnitude: near-zero intensity
    /// components give large ratios that say little. Both are reported, so a file whose
    /// differences all sit below that floor does not read as 0.
    rel: f64,
    /// The largest distance in `f32` steps between two finite values of the same sign.
    ulps: u32,
}

impl Spread {
    fn file(&mut self, pairs: &[(f32, f32)]) {
        let top = pairs
            .iter()
            .flat_map(|&(a, b)| [a, b])
            .filter(|v| v.is_finite())
            .fold(0f32, |m, v| m.max(v.abs()));
        for &(a32, b32) in pairs {
            if a32.to_bits() == b32.to_bits() {
                continue;
            }
            self.n += 1;
            if a32.is_nan() && b32.is_nan() {
                continue;
            }
            self.numeric += 1;
            if a32.is_finite()
                && b32.is_finite()
                && a32.is_sign_negative() == b32.is_sign_negative()
            {
                self.ulps = self.ulps.max(a32.to_bits().abs_diff(b32.to_bits()));
            }
            let (a, b) = (f64::from(a32), f64::from(b32));
            let d = (a - b).abs();
            self.abs = self.abs.max(d);
            let m = a.abs().max(b.abs());
            if m > 0.0 {
                self.rel_all = self.rel_all.max(d / m);
                if m >= 1e-3 * f64::from(top) {
                    self.rel = self.rel.max(d / m);
                }
            }
        }
    }
}

fn value_spread(theirs: &Outputs, ours: &Outputs) -> Spread {
    let mut s = Spread::default();
    for (k, t) in theirs {
        let Some(o) = ours.get(k) else { continue };
        if t == o {
            continue;
        }
        let mut pairs = Vec::new();
        if k.ends_with(".csbin") {
            if let (Ok(t), Ok(o)) = (csbin::read(t), csbin::read(o)) {
                for (rt, ro) in t.receivers.iter().zip(&o.receivers) {
                    for (ft, fo) in rt.faces.iter().zip(&ro.faces) {
                        for (a, b) in ft.records.iter().zip(fo.records.iter()) {
                            pairs.push((a.energy, b.energy));
                        }
                    }
                }
                s.file(&pairs);
                continue;
            }
        } else if let (Ok(t), Ok(o)) = (gabe::read(t), gabe::read(o)) {
            for (ct, co) in t.columns.iter().zip(&o.columns) {
                if let (
                    gabe::ColumnData::Float { values: vt, .. },
                    gabe::ColumnData::Float { values: vo, .. },
                ) = (&ct.data, &co.data)
                {
                    pairs.extend(vt.iter().copied().zip(vo.iter().copied()));
                }
            }
            s.file(&pairs);
            continue;
        }
        s.n += 1;
        s.numeric += 1;
        s.abs = f64::NAN;
        s.rel_all = f64::NAN;
    }
    s
}

